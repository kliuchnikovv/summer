"""Ports: abstract interfaces the application depends on, implemented by infrastructure.

Dependencies point inward — the application knows these Protocols, never the concrete
Redis / OpenRouter / FastAPI adapters that satisfy them.
"""
from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Protocol, runtime_checkable

from app.domain.models import DocStatus, DocumentResult, DocumentState, ParserType, Principal


@runtime_checkable
class DocumentRepository(Protocol):
    async def create(
        self, *, doc_id: str, principal: str, parser: ParserType, filename: str,
        content_hash: str, batch_id: str, raw_bytes: bytes, page_count: int | None,
    ) -> tuple[DocumentState, bool]: ...
    async def get_state(self, doc_id: str) -> DocumentState | None: ...
    async def get_result(self, doc_id: str) -> DocumentResult | None: ...
    async def get_raw(self, doc_id: str) -> bytes | None: ...
    async def set_status(self, doc_id: str, status: DocStatus, *, error: str | None = None,
                         page_count: int | None = None) -> None: ...
    async def save_page(self, doc_id: str, page_no: int, markdown: str) -> None: ...
    async def save_summary(self, doc_id: str, summary: str) -> None: ...
    async def clear_pages(self, doc_id: str) -> None: ...
    async def get_pages(self, doc_id: str) -> list[str]: ...
    async def release_inflight(self, principal: str, doc_id: str) -> None: ...
    async def batch_doc_ids(self, batch_id: str) -> list[str]: ...
    async def list_documents(self, principal: str, limit: int) -> list[DocumentState]: ...


@runtime_checkable
class JobQueue(Protocol):
    async def ensure_group(self) -> None: ...
    async def enqueue(self, doc_id: str, parser: ParserType) -> str: ...
    async def read(self, consumer: str, count: int = 1) -> list[tuple[str, dict]]: ...
    async def ack(self, msg_id: str) -> None: ...
    async def reclaim_stale(self, consumer: str, count: int = 10) -> list[tuple[str, dict]]: ...
    async def delivery_count(self, msg_id: str) -> int: ...
    async def dead_letter(self, msg_id: str, doc_id: str, parser: str, reason: str) -> None: ...


@runtime_checkable
class Parser(Protocol):
    name: ParserType
    def iter_pages(self, raw: bytes) -> AsyncIterator[tuple[int, str]]: ...


class ParserRegistry(Protocol):
    def get(self, parser: ParserType) -> Parser: ...


class Summarizer(Protocol):
    async def summarize(self, pages: list[str]) -> str: ...


class PdfInspector(Protocol):
    def count_pages(self, raw: bytes) -> int:  # raises domain InvalidPDF
        ...


class RateLimiter(Protocol):
    async def check_burst(self, principal: str) -> None: ...
    async def check_daily(self, principal: str, limit: int | None = None) -> None: ...
    async def try_acquire_slot(self, principal: str, doc_id: str) -> bool: ...
    async def release_slots(self, principal: str, doc_ids: list[str]) -> None: ...


class SessionStore(Protocol):
    async def create(self, username: str, password: str) -> tuple[str, str, int]: ...
    async def destroy(self, token: str) -> None: ...
    async def principal_from_token(self, token: str) -> Principal | None: ...
    def principal_from_api_key(self, key: str) -> Principal | None: ...
